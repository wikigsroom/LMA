"""Reproduce signed FlexiCubes topology tables from locked publisher source."""
import ast
import hashlib
import json
from pathlib import Path
from spatial_portable import Source,ROOT

REL='sam3d_objects/model/backbone/tdfy_dit/representations/mesh/flexicubes/tables.py'


def tables():
    source=Source('D08');_,text=source.read(REL)
    values={}
    for node in ast.parse(text).body:
        if isinstance(node,ast.Assign) and len(node.targets)==1 and isinstance(node.targets[0],ast.Name):
            values[node.targets[0].id]=ast.literal_eval(node.value)
    return values,source.files[REL]['sha256']


def render():
    data,digest=tables()
    header=['// Copyright (c) Meta Platforms, Inc. and affiliates.',
            '// Copyright (c) 2025 NVIDIA CORPORATION & AFFILIATES.',
            '// Licensed under Apache-2.0; see third_party/notices.',
            '// Generated by tools/flexicubes_tables.py; source SHA256 '+digest,
            '#pragma once','namespace lma_flexicubes_tables {']
    for key,shape in [('dmc_table','[256][4][7]'),('num_vd_table','[256]'),('check_table','[256][5]')]:
        value=json.dumps(data[key],separators=(',',':')).replace('[','{').replace(']','}')
        header.append('inline constexpr int '+key+shape+'='+value+';')
    return '\r\n'.join(header+['}',''])


if __name__=='__main__':
    target=ROOT/'native/spatial/flexicubes_tables.hpp'
    target.write_bytes(render().encode('utf-8'))
    print(json.dumps(dict(path=target.relative_to(ROOT).as_posix(),sha256=hashlib.sha256(target.read_bytes()).hexdigest())))
