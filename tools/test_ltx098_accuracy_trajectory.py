"""Bind three trained native A/B/A stage chains to the frozen original gates.

Text is generated by the separately verified A/B/A candidate producer. Each
invocation here executes new native sampling, noise, layout, VAE and frame
stages; review mode revalidates the recorded captures without claiming new jobs.
This is offline host numerical evidence, not Android or video-quality evidence.
"""
import argparse
import json
from pathlib import Path

from compare_ltx098_accuracy_decode import inputs as decode_inputs, run as decode
from compare_ltx098_accuracy_sampling import candidate_details, compare as sample
from evidence import current, fingerprint
from fetch_ltx098_text import sha
from ltx098_pipeline import write

ROOT = Path(__file__).resolve().parents[1]


def inputs():
    return {**decode_inputs(), **fingerprint('tools/test_ltx098_accuracy_trajectory.py')}


def run(variant, reference, review=None, initial_sampling=None):
    before = inputs()
    if review and initial_sampling: raise ValueError('Choose review or first-stage recovery')
    if initial_sampling and not initial_sampling.resolve().is_relative_to(ROOT / 'build'):
        raise ValueError('Recovered sampling must stay below build/')
    if review:
        review = review.resolve()
        if not review.is_relative_to(ROOT / 'build'): raise ValueError('Review must stay below build/')
        prior = json.loads(review.read_text(encoding='utf-8'))
        current(prior['input_fingerprint'])
        if prior['input_fingerprint'] != before or prior['variant'] != variant or len(prior['jobs']) != 3:
            raise ValueError('Different captured trajectory')
    candidate_path, candidate_inputs = candidate_details(variant)
    candidate = json.loads(candidate_path.read_text(encoding='utf-8'))
    current(candidate['input_fingerprint'])
    if candidate['input_fingerprint'] != candidate_inputs or not candidate['aba_bitwise_identical']:
        raise ValueError('Require current complete trained T5 A/B/A')
    jobs = []
    for index, case_index in enumerate([0, 1, 0]):
        print('Native full-chain accuracy job', index, 'case', case_index, flush=True)
        earlier = prior['jobs'][index] if review else None
        sample_capture = ROOT / earlier['sampling']['capture_directory'] if earlier else None
        if index == 0 and initial_sampling: sample_capture = initial_sampling
        sample(variant, reference, case_index, sample_capture)
        path = ROOT / 'build/ltx098-text-accuracy-sampling' / (variant + '-case-' + str(case_index) + '-results.json')
        sampling = json.loads(path.read_text(encoding='utf-8'))
        decode_capture = ROOT / earlier['decode']['capture_directory'] if earlier else None
        decode(variant, reference, case_index, decode_capture)
        path = ROOT / 'build/ltx098-text-accuracy-video' / (variant + '-case-' + str(case_index) + '-results.json')
        decoded = json.loads(path.read_text(encoding='utf-8'))
        if (sampling['candidate_sha256'] != sha(candidate_path) or
            decoded['binding']['candidate_sha256'] != sha(candidate_path) or
            sampling['candidate_caption_sha256'] != candidate['jobs'][index]['caption_sha256']):
            raise ValueError('Text/sampling/decode identities differ')
        jobs.append(dict(index=index, case=case_index, text=candidate['jobs'][index], sampling=sampling, decode=decoded))
    for key in ['sampling', 'decode']:
        if jobs[0][key]['capture_directory'] == jobs[2][key]['capture_directory']:
            raise ValueError('Repeated A must have independently executed native children')
    aba = all(jobs[0]['decode']['files'][name]['sha256'] == jobs[2]['decode']['files'][name]['sha256'] for name in
              ['initial-tokens.f32', 'decode-noise.f32', 'denoised-ncthw.f32', 'decoded-ncthw.f32', 'frames.lma'])
    aba = aba and jobs[0]['sampling']['files']['latents.f32']['sha256'] == jobs[2]['sampling']['files']['latents.f32']['sha256']
    if not aba: raise ValueError('Native A/B/A tensor/frame outputs differ')
    failures = [dict(job=i, files=j['decode']['failures']) for i, j in enumerate(jobs) if j['decode']['failures']]
    current(before)
    executed = sum(job['sampling']['native_children_executed_this_invocation'] + job['decode']['native_children_executed_this_invocation'] for job in jobs)
    report = dict(schema='lma.ltx098-accuracy-trajectory/1', variant=variant, jobs=jobs, numeric_failures=failures,
                  candidate_sha256=sha(candidate_path), original_oracle_sha256=candidate['original_oracle_sha256'],
                  distinct_prompts=2, aba_bitwise_identical=True, captured_trained_text_children=3,
                  captured_trained_sampling_children=3, captured_native_decode_children=12,
                  native_children_executed_this_invocation=executed, capture_reused=bool(review),
                  first_sampling_recovered=bool(initial_sampling),
                  full_chain_original_numeric_gates_passed=not failures, acceptance_gates_changed=False,
                  production_source_changed=False, engine_registered=False, packaged_in_apk=False,
                  physical_android=False, video_quality_accepted=False, complete_release_accepted=False,
                  input_fingerprint=before)
    out = ROOT / 'build/ltx098-text-accuracy-trajectories'; out.mkdir(exist_ok=True)
    write(out / (variant + '-results.json'), report)
    print(json.dumps(dict(variant=variant, full_chain_original_numeric_gates_passed=not failures,
                          aba_bitwise_identical=True, failures=failures)), flush=True)
    return 0 if not failures else 1


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--variant', choices=['norm', 'activation', 'order', 'staging', 'f32'], required=True)
    parser.add_argument('--reference', type=Path, required=True)
    parser.add_argument('--review', type=Path, help='Revalidate a complete saved trajectory record')
    parser.add_argument('--initial-sampling', type=Path, help='Recover a completed first sampling stage after a later-stage failure')
    args = parser.parse_args()
    raise SystemExit(run(args.variant, args.reference, args.review, args.initial_sampling))
