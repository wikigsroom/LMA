"""Compile the approved UI10 tokens into offline WebView assets; no network access."""
import hashlib
import json
from evidence import ROOT, version


def build():
    source = ROOT / 'docs/design/tokens.json'
    tokens = json.loads(source.read_text(encoding='utf-8'))
    assert tokens['selectedStyle'] == 10 and set(tokens['themes']) == {'dark', 'light'}
    lines = ['/* Generated by tools/build_mica.py from the approved UI10 tokens. */']
    for theme, values in tokens['themes'].items():
        lines += ['.lma-mica[data-theme="' + theme + '"] {', '  color-scheme: ' + theme + ';']
        for name, value in values.items():
            name = ''.join('-' + c.lower() if c.isupper() else c for c in name)
            lines.append('  --lma-' + name + ': ' + value + ';')
        lines += ['  --lma-shadow: ' + tokens['material']['shadow'][theme] + ';', '}']
    target = ROOT / 'app/src/main/assets/mica-tokens.css'
    target.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    info = dict(schema='lma.mica-design/1', version=version(), style=10,
                design_version=tokens['designVersion'], source='docs/design/tokens.json',
                source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
                themes=list(tokens['themes']), logo=21, slogan='04')
    (target.parent / 'mica-design.json').write_text(json.dumps(info, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(info))


if __name__ == '__main__':
    build()
